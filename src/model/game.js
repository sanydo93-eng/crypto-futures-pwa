/**
 * Вероятность выиграть гейм на своей подаче.
 *
 * Модель считает очки независимыми с постоянной вероятностью p. Для тенниса это
 * близко к правде: Klaassen & Magnus (2001) на данных Уимблдона показали, что
 * отклонения от независимости существуют, но малы.
 *
 * Гейм выигрывается либо «всухую» до 40:0/40:15/40:30, либо через ровно.
 */
export function gameWinProbability(p) {
  const q = 1 - p;

  // Выигрыш без ровно: 4:0, 4:1 (C(4,1)=4 расстановки), 4:2 (C(5,2)=10).
  const straight = p ** 4 * (1 + 4 * q + 10 * q * q);

  // Приход к ровно (3:3 по очкам): C(6,3)=20 расстановок.
  const reachDeuce = 20 * p ** 3 * q ** 3;

  // Из ровно: D = p^2 + 2pq*D  =>  D = p^2 / (p^2 + q^2).
  // Знаменатель минимален при p=0.5 и равен 0.5, поэтому в ноль не обращается.
  const fromDeuce = (p * p) / (p * p + q * q);

  return straight + reachDeuce * fromDeuce;
}
